// Copies the Phosphor Bold subset into assets/Icons (inked #0b0c0a for <img> use)
// and writes components/src/icons.ts (path data for the inline Icon component).
//   node scripts/icons.mjs   (needs @phosphor-icons/core installed)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const ROOT = process.env.DS_ROOT ? path.resolve(process.env.DS_ROOT) : path.resolve(here, '..');
function findPackage(start, name) {
  for (let dir = start; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, 'node_modules', name);
    if (fs.existsSync(candidate)) return candidate;
    if (dir === path.dirname(dir)) throw new Error(`${name} is not installed`);
  }
}
const SRC = path.join(findPackage(here, '@phosphor-icons/core'), 'assets', 'bold');
const INK = '#0b0c0a';

export const ICON_NAMES = [
  // catalog
  'lockers', 'jar-label', 'drop', 'package', 'storefront', 'shopping-cart-simple', 'tag', 'truck', 'barbell', 'pill', 'lightning',
  // admin
  'squares-four', 'chart-bar', 'chart-line-up', 'users-three', 'user', 'tray', 'envelope-simple', 'chat-text', 'phone',
  'map-pin', 'buildings', 'gear', 'sign-out', 'lock-simple', 'shield-check', 'bell', 'text-aa',
  // actions
  'plus', 'minus', 'x', 'check', 'trash', 'pencil-simple', 'magnifying-glass', 'funnel-simple', 'eye', 'eye-slash',
  'copy-simple', 'upload-simple', 'download-simple', 'arrows-clockwise', 'dots-three', 'list', 'link-simple',
  // direction
  'caret-down', 'caret-up', 'caret-left', 'caret-right', 'caret-up-down', 'arrow-right', 'arrow-left', 'arrow-up-right',
  'trend-up', 'trend-down',
  // status
  'warning', 'warning-circle', 'info', 'check-circle', 'x-circle', 'clock', 'calendar-blank', 'image', 'star',
  'currency-dollar', 'receipt', 'question',
];

const outDir = path.join(ROOT, 'assets', 'Icons');
fs.mkdirSync(outDir, { recursive: true });
const map = {};
for (const name of ICON_NAMES) {
  const svg = fs.readFileSync(path.join(SRC, `${name}-bold.svg`), 'utf8').trim();
  const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
  const paths = [...inner.matchAll(/<path d="([^"]+)"\s*\/>/g)].map((m) => m[1]);
  if (!paths.length || inner.replace(/<path d="[^"]+"\s*\/>/g, '').trim()) throw new Error(`${name}: unexpected SVG structure`);
  if (!svg.includes('fill="currentColor"')) throw new Error(`${name}: no currentColor fill to ink`);
  map[name] = paths.join('');
  fs.writeFileSync(path.join(outDir, `${name}.svg`), svg.replace('fill="currentColor"', `fill="${INK}"`) + '\n');
}
const names = Object.keys(map);
const ts = [
  '// Phosphor Icons, Bold weight (MIT). Generated by scripts/icons.mjs from @phosphor-icons/core.',
  '// Path data on a 256 x 256 grid, drawn with fill.',
  '',
  '/** A glyph name from the Phosphor Bold subset kept in `assets/Icons`. */',
  'export type IconName =',
  ...names.map((k, i) => `  | '${k}'${i === names.length - 1 ? ';' : ''}`),
  '',
  'export const ICONS: Record<IconName, string> = {',
  ...Object.entries(map).map(([k, d]) => `  '${k}': '${d}',`),
  '};',
  '',
].join('\n');
fs.mkdirSync(path.join(ROOT, 'components', 'src'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'components', 'src', 'icons.ts'), ts);
console.log(`${ICON_NAMES.length} icons -> assets/Icons, components/src/icons.ts (${ts.length} bytes)`);
